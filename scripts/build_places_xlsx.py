def build_university_rows():
    rows = []
    for zone, detail, kind, tags in UNIVERSITY:
        name = detail if detail.startswith("대학교 ") else f"대학교 {detail}"
        rows.append([name, zone, detail, kind, tags])
    return rows


def add_sheet(wb, title, headers, rows, widths):
    ws = wb.create_sheet(title)
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    head = []
    for h in ["번호"] + headers:
        c = WriteOnlyCell(ws, value=h)
        c.font = HFONT
        c.fill = HFILL
        c.alignment = Alignment(horizontal="center")
        head.append(c)
    ws.append(head)
    for i, r in enumerate(rows, start=1):
        cells = []
        for v in [i] + r:
            c = WriteOnlyCell(ws, value=v)
            c.font = BFONT
            cells.append(c)
        ws.append(cells)
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(headers) + 1)}{len(rows) + 1}"
    print(f"  시트 {title}: {len(rows):,}행")


